#!/usr/bin/env python3
"""
Bridge 框架开发工具 — ABI 配置管理

管理不同 Android 架构的编译配置（Bridge / PyBridge 共用）。
"""

import json
import os
from dataclasses import dataclass, asdict
from typing import Dict, List, Optional


@dataclass
class ABIConfig:
    """Android ABI 配置"""
    name: str                    # ABI 名称 (arm64-v8a, x86_64 等)
    triple: str                  # GNU target triple
    arch: str                    # 架构名
    api_level: int               # 最低 Android API level
    ndk_cc: str                  # NDK C 编译器路径模板
    ndk_cxx: str                 # NDK C++ 编译器路径模板
    python_arch: str             # Python 架构名
    qemu_user: Optional[str] = None  # QEMU 用户态模拟器（用于测试）


# 支持的 ABI 配置
ABI_CONFIGS: Dict[str, ABIConfig] = {
    "arm64-v8a": ABIConfig(
        name="arm64-v8a",
        triple="aarch64-linux-android",
        arch="aarch64",
        api_level=24,
        ndk_cc="{toolchain}/bin/aarch64-linux-android{api}-clang",
        ndk_cxx="{toolchain}/bin/aarch64-linux-android{api}-clang++",
        python_arch="aarch64",
        qemu_user="qemu-aarch64",
    ),
    "armeabi-v7a": ABIConfig(
        name="armeabi-v7a",
        triple="arm-linux-androideabi",
        arch="armv7a",
        api_level=24,
        ndk_cc="{toolchain}/bin/armv7a-linux-androideabi{api}-clang",
        ndk_cxx="{toolchain}/bin/armv7a-linux-androideabi{api}-clang++",
        python_arch="armv7l",
        qemu_user="qemu-arm",
    ),
    "x86_64": ABIConfig(
        name="x86_64",
        triple="x86_64-linux-android",
        arch="x86_64",
        api_level=24,
        ndk_cc="{toolchain}/bin/x86_64-linux-android{api}-clang",
        ndk_cxx="{toolchain}/bin/x86_64-linux-android{api}-clang++",
        python_arch="x86_64",
        qemu_user="qemu-x86_64",
    ),
    "x86": ABIConfig(
        name="x86",
        triple="i686-linux-android",
        arch="i686",
        api_level=24,
        ndk_cc="{toolchain}/bin/i686-linux-android{api}-clang",
        ndk_cxx="{toolchain}/bin/i686-linux-android{api}-clang++",
        python_arch="i686",
        qemu_user="qemu-i386",
    ),
}


def get_abi_config(abi: str) -> ABIConfig:
    """获取 ABI 配置"""
    if abi not in ABI_CONFIGS:
        raise ValueError(f"Unsupported ABI: {abi}. Supported: {list(ABI_CONFIGS.keys())}")
    return ABI_CONFIGS[abi]


def get_ndk_toolchain(ndk_path: str, abi: str, api_level: Optional[int] = None) -> Dict[str, str]:
    """
    获取 NDK 工具链路径

    Returns:
        包含 CC, CXX, AR, RANLIB 等路径的字典
    """
    config = get_abi_config(abi)
    api = api_level or config.api_level
    toolchain = f"{ndk_path}/toolchains/llvm/prebuilt/linux-x86_64"

    return {
        "CC": config.ndk_cc.format(toolchain=toolchain, api=api),
        "CXX": config.ndk_cxx.format(toolchain=toolchain, api=api),
        "AR": f"{toolchain}/bin/llvm-ar",
        "RANLIB": f"{toolchain}/bin/llvm-ranlib",
        "STRIP": f"{toolchain}/bin/llvm-strip",
        "READELF": f"{toolchain}/bin/llvm-readelf",
        "NM": f"{toolchain}/bin/llvm-nm",
        "LD": f"{toolchain}/bin/ld.lld",
    }


def list_supported_abis() -> List[str]:
    """列出所有支持的 ABI"""
    return list(ABI_CONFIGS.keys())


def generate_cmake_toolchain(abi: str, ndk_path: str, api_level: Optional[int] = None) -> str:
    """
    生成 CMake 工具链文件内容

    用于交叉编译原生扩展模块。
    """
    config = get_abi_config(abi)
    api = api_level or config.api_level

    return f"""# Bridge CMake Toolchain - {abi}
# Auto-generated by bridge tools

set(CMAKE_SYSTEM_NAME Android)
set(CMAKE_SYSTEM_PROCESSOR {config.arch})
set(ANDROID_ABI {abi})
set(ANDROID_PLATFORM android-{api})
set(ANDROID_NDK {ndk_path})
set(ANDROID_STL c++_shared)

set(CMAKE_C_COMPILER {config.ndk_cc.format(toolchain=f'{ndk_path}/toolchains/llvm/prebuilt/linux-x86_64', api=api)})
set(CMAKE_CXX_COMPILER {config.ndk_cxx.format(toolchain=f'{ndk_path}/toolchains/llvm/prebuilt/linux-x86_64', api=api)})

set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
"""


if __name__ == "__main__":
    import sys

    if len(sys.argv) < 2:
        print("Usage: abi_config.py <command> [args]")
        print("Commands: list, info <abi>, toolchain <abi> <ndk>")
        sys.exit(1)

    cmd = sys.argv[1]

    if cmd == "list":
        for abi in list_supported_abis():
            config = get_abi_config(abi)
            print(f"  {abi:15s} {config.triple:30s} API {config.api_level}")

    elif cmd == "info":
        abi = sys.argv[2] if len(sys.argv) > 2 else "arm64-v8a"
        config = get_abi_config(abi)
        print(json.dumps(asdict(config), indent=2))

    elif cmd == "toolchain":
        abi = sys.argv[2] if len(sys.argv) > 2 else "arm64-v8a"
        ndk = sys.argv[3] if len(sys.argv) > 3 else os.environ.get("ANDROID_NDK", "")
        if not ndk:
            print("Error: NDK path required")
            sys.exit(1)
        tools = get_ndk_toolchain(ndk, abi)
        for k, v in tools.items():
            print(f"  {k}: {v}")
